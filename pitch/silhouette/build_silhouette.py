def main():
    svg = open(os.path.join(HERE, "silhouette.svg"), encoding="utf8").read()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S).strip()
    data = json.load(open(os.path.join(HERE, "fiches.json"), encoding="utf8"))
    ids_svg = re.findall(r'id="(region-[a-z]+)"', svg)
    ids_json = [r["id"] for r in data["regions"]]
    if sorted(ids_svg) != sorted(ids_json):
        raise SystemExit(f"ERROR: ids differ. svg={ids_svg} json={ids_json}")
    short = {r["id"]: r["title"].split(":")[0] for r in data["regions"]}
    items = "".join(f'<li><button type="button" data-region="{i}" aria-pressed="false">{html.escape(short[i])}</button></li>'
                    for i in ids_json)
    out = (TEMPLATE.replace("__BANNER__", "SYNTHETIC DATA — demo story, not a real astronaut")
           .replace("__SVG__", svg).replace("__LIST__", items)
           .replace("__DATA__", json.dumps(data, ensure_ascii=False).replace("</", "<\\/")))
    path = os.path.join(HERE, "silhouette_demo.html")
    open(path, "w", encoding="utf8").write(out)
    print(f"OK: pitch/silhouette/silhouette_demo.html ({len(ids_json)} regions)")


if __name__ == "__main__":
    main()
